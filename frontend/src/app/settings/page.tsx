"use client";

import { Monitor, Moon, Sun } from "lucide-react";
import { ALL_TOPICS, TOPIC_LABELS, useTheme, useTopics, type ThemeChoice } from "@/lib/preferences";
import { Page } from "@/components/shell/Page";
import { cn } from "@/lib/utils";

const THEMES: { value: ThemeChoice; label: string; icon: typeof Sun }[] = [
  { value: "light", label: "Light", icon: Sun },
  { value: "dark", label: "Dark", icon: Moon },
  { value: "system", label: "Match system", icon: Monitor },
];

const SHORTCUTS: [string, string][] = [
  ["J", "Next story"],
  ["K", "Previous story"],
  ["S", "Save or unsave the open story"],
  ["Esc", "Close an explanation"],
  ["/", "Search"],
];

function Section({
  title,
  description,
  children,
}: {
  title: string;
  description?: string;
  children: React.ReactNode;
}) {
  return (
    <section className="grid gap-6 border-t py-8 md:grid-cols-[240px_1fr]">
      <div>
        <h2 className="font-display text-[15px] font-semibold">{title}</h2>
        {description && (
          <p className="mt-1 text-[13.5px] leading-relaxed text-text-tertiary">{description}</p>
        )}
      </div>
      <div>{children}</div>
    </section>
  );
}

export default function SettingsPage() {
  const { theme, setTheme } = useTheme();
  const [topics, setTopics] = useTopics();

  const toggleTopic = (t: string) => {
    const next = topics.includes(t as (typeof ALL_TOPICS)[number])
      ? topics.filter((x) => x !== t)
      : [...topics, t];
    setTopics(next.length ? next : [...ALL_TOPICS]);
  };

  return (
    <Page title="Settings">
      <Section title="Appearance">
        <div
          role="radiogroup"
          aria-label="Theme"
          className="inline-flex rounded-lg border bg-background p-1"
        >
          {THEMES.map(({ value, label, icon: Icon }) => (
            <button
              key={value}
              type="button"
              role="radio"
              aria-checked={theme === value}
              onClick={() => setTheme(value)}
              className={cn(
                "flex h-8 items-center gap-2 rounded-md px-3.5 text-[13px] font-medium transition-colors",
                theme === value
                  ? "bg-accent-primary text-on-accent"
                  : "text-text-secondary hover:text-foreground",
              )}
            >
              <Icon size={15} /> {label}
            </button>
          ))}
        </div>
      </Section>

      <Section title="Topics" description="Shown as filters above Today's stories.">
        <div className="flex flex-wrap gap-2">
          {ALL_TOPICS.map((t) => {
            const on = topics.includes(t);
            return (
              <button
                key={t}
                type="button"
                aria-pressed={on}
                onClick={() => toggleTopic(t)}
                className={cn(
                  "h-9 rounded-full border px-4 text-[14px] font-medium transition-colors",
                  on
                    ? "border-accent-primary bg-accent-primary text-on-accent"
                    : "text-text-secondary hover:border-accent-secondary hover:text-foreground",
                )}
              >
                {TOPIC_LABELS[t]}
              </button>
            );
          })}
        </div>
      </Section>

      <Section title="Keyboard shortcuts">
        <dl className="grid max-w-[420px] grid-cols-[64px_1fr] gap-y-2.5 text-[14px]">
          {SHORTCUTS.map(([key, what]) => (
            <div key={key} className="contents">
              <dt>
                <kbd className="inline-flex h-6 min-w-[24px] items-center justify-center rounded border bg-background px-1.5 font-body text-[12px]">
                  {key}
                </kbd>
              </dt>
              <dd className="text-text-secondary">{what}</dd>
            </div>
          ))}
        </dl>
      </Section>

      <Section title="About">
        <p className="max-w-[56ch] text-[14px] leading-relaxed text-text-secondary">
          samā4 explains the people, places and ideas in the news as you read. Explanations are
          generated by AI from Wikipedia and recent reporting, so check anything important against
          the source.
        </p>
        <p className="mt-3 text-[13px] text-text-tertiary">Version 2.0</p>
      </Section>
    </Page>
  );
}
